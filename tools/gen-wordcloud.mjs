// Generate a word-cloud SVG with d3-cloud, laid out inside headless Chrome so
// that text metrics come from the real webfont the decks use (Urbanist).
//
//   npm i puppeteer-core d3-cloud          (not vendored; run from this dir)
//   node gen-wordcloud.mjs <words.json> <out.svg> [accent]
//
//   WC_W / WC_H tune the layout canvas. The canvas only shapes the cloud: the
//   viewBox is cropped to the ink afterwards. Wider canvas gives a wider cloud.
//   1500x520 is what the day-0 slide uses.
//
// words.json is [["w5","pipelines"], ["w2","latency"], ...]; the tier sets both
// size and colour. Deterministic: same input gives byte-identical output.
import puppeteer from 'puppeteer-core';
import fs from 'node:fs';
import path from 'node:path';

const WORDS  = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const OUT    = path.resolve(process.argv[3]);
const ACCENT = process.argv[4] || '#dc0069';
const HERE   = path.dirname(new URL(import.meta.url).pathname);  // node_modules lives here
const W = Number(process.env.WC_W || 1180), H = Number(process.env.WC_H || 560);

// Colours are baked in rather than left to CSS: an <object>-embedded SVG cannot
// see the host page's custom properties. Re-run with a different accent to
// retheme.
const mix = (hex, pct) => {
  const n = parseInt(hex.slice(1), 16);
  const ch = s => Math.round((((n >> s) & 255) * pct) + 255 * (1 - pct));
  return '#' + [16, 8, 0].map(s => ch(s).toString(16).padStart(2, '0')).join('');
};
const TIER = {
  w5: [70, ACCENT, 800], w4: [48, ACCENT, 800],
  w3: [34, mix(ACCENT, 0.72), 600],
  w2: [25, '#8c8c8c', 400], w1: [19, '#b3b3b3', 400],
};

const launch = () => puppeteer.launch({
  executablePath: '/bin/google-chrome', headless: 'new', args: ['--no-sandbox'],
});

// ---- pass 1: lay the words out --------------------------------------------
const browser = await launch();
const page = await browser.newPage();
await page.setContent(
  '<!doctype html><meta charset="utf-8">' +
  '<style>@import url(https://fonts.googleapis.com/css?family=Urbanist:400,600,800);' +
  'body{margin:0;font-family:Urbanist,sans-serif}</style><body></body>',
  { waitUntil: 'networkidle2' });
await page.evaluate(async () => {
  await Promise.all([400, 600, 800].map(w => document.fonts.load(w + ' 40px Urbanist')));
  await document.fonts.ready;
});
await page.addScriptTag({ path: HERE + '/node_modules/d3-cloud/build/d3.layout.cloud.js' });

const placed = await page.evaluate((words, tier, W, H) => new Promise(resolve => {
  const items = words.map(([t, text]) => ({
    text, tier: t, size: tier[t][0], fill: tier[t][1], weight: tier[t][2],
  }));
  d3.layout.cloud()
    .size([W, H]).words(items).padding(3)
    .font('Urbanist').fontWeight(d => d.weight).fontSize(d => d.size)
    // headline terms stay horizontal; the tail may turn, which is what makes it
    // read as a cloud rather than a list
    .rotate(d => (d.tier === 'w5' || d.tier === 'w4') ? 0
                 : (Math.random() < 0.28 ? 90 : 0))
    .spiral('archimedean')
    .random(() => 0.5)                        // deterministic layout
    .on('end', out => resolve(out.map(d => ({
      text: d.text, x: Math.round(d.x * 100) / 100, y: Math.round(d.y * 100) / 100,
      rotate: d.rotate, size: d.size, fill: d.fill, weight: d.weight, tier: d.tier,
    }))))
    .start();
}), WORDS, TIER, W, H);
await browser.close();

const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const body = placed.map(d =>
  '    <text class="' + d.tier + '" text-anchor="middle" fill="' + d.fill +
  '" font-size="' + d.size + '" font-weight="' + d.weight +
  '" transform="translate(' + d.x + ',' + d.y + ')' +
  (d.rotate ? ' rotate(' + d.rotate + ')' : '') + '">' + esc(d.text) + '</text>'
).join('\n');

const render = (vb, w, h) =>
`<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/gen-wordcloud.mjs; regenerate rather than hand-edit.
     Layout: d3-cloud (Archimedean spiral, pixel-level collision), measured
     against Urbanist so it matches the deck body font. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" width="${w}" height="${h}"
     role="img" aria-label="Topics covered in weeks 1 to 3">
  <title>Data pipelines: topics covered in weeks 1-3</title>
  <g transform="translate(${W / 2},${H / 2})"
     font-family="Urbanist, Inter, Arimo, Helvetica, sans-serif">
${body}
  </g>
</svg>
`;

fs.writeFileSync(OUT, render(`0 0 ${W} ${H}`, W, H));

// ---- pass 2: crop the viewBox to the ink ----------------------------------
// The spiral leaves slack around the cloud, so the nominal canvas is much
// larger than the drawing; without this the slide scales mostly whitespace.
const b2 = await launch();
const pg = await b2.newPage();
await pg.goto('file://' + OUT, { waitUntil: 'networkidle2' });
await pg.evaluate(() => document.fonts.ready);
const bb = await pg.evaluate(() => {
  const g = document.querySelector('svg > g').getBBox();
  return { x: g.x, y: g.y, w: g.width, h: g.height };
});
await b2.close();

const pad = 8;
const vb = [
  Math.floor(bb.x + W / 2 - pad), Math.floor(bb.y + H / 2 - pad),
  Math.ceil(bb.w + 2 * pad),      Math.ceil(bb.h + 2 * pad),
];
fs.writeFileSync(OUT, render(vb.join(' '), vb[2], vb[3]));

const missing = WORDS.map(w => w[1]).filter(t => !placed.some(p => p.text === t));
console.log(`placed ${placed.length}/${WORDS.length}; viewBox ${vb.join(' ')}`);
if (missing.length) console.log('DROPPED (canvas too small):', missing.join(', '));
